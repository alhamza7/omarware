/**
 * Returns a deterministic quote based on the current hour.
 * The quote changes every hour using a simple hash of the
 * current date+hour as a seed, so all users see the same
 * quote at the same hour on the same day.
 */
export function getHourlyQuote(): string {
  const now = new Date();
  const seed = now.getFullYear() * 1000000
    + (now.getMonth() + 1) * 10000
    + now.getDate() * 100
    + now.getHours();
  const idx = seed % quotes.length;
  return quotes[idx];
}

